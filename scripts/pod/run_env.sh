# The packed token ladder Experiment 1 trains on. Small (20 MB) and pulled
# straight from the relay rather than tarred into the transfer bundle, because
# it is the experiment's data identity and must arrive hash-checked.
LADDER_PREFIX=stage3_recovery_corpus_v2/ladder_uniform
LADDER_DEST=artifacts/stage3/ladder_uniform

# Must be exported: verify_and_report.py reads it from the environment, and a
# non-exported value made a whole session fail upload verification against a
# path nothing had written to.
export HF_PREFIX_BASE=e1_scaling_20260801

# Pre-registered abort rule (logs/PROPOSAL.md §7): stop an arm whose primary-val
# CE at the first eval exceeds its step-0 value, rather than retuning mid-session.
ABORT_ARMS=""
ABORT_CHECK_STEP=25

# --- budget guard (AGENTS.md P6/P12) --------------------------------------
# The session is capped at $60 total across both pods. A pod is created with a
# hard --terminate-after at POD_DEADLINE_HOURS so the cap holds even if every
# other guard fails: 2 pods x 30.0 h x $0.99/h = $59.40.
#
# The orchestrator additionally refuses to *start* an arm it cannot finish
# before the deadline, so a cut session ends with completed uploads rather than
# a pod killed mid-transfer.
POD_DEADLINE_HOURS=30.0
HOURLY_USD=0.99
SECONDS_PER_STEP=4.3          # measured, block_len 8192 + gradient checkpointing
POST_RUN_RESERVE_MIN=25       # evals + hashing + upload for one arm

SESSION_COMMIT_SUBJECT="stage3: ${SESSION} session — logs"
SESSION_COMMIT_BODY=""

# Left EMPTY on purpose — verify_and_report.py is verify-only, and a session
# must supply its own write-up rather than inherit another experiment's rules.
REPORT_CMD=

# Paths setup.sh checks exist after the bundle + data land.
HOLDOUT=data/warmup/holdout_v1.jsonl
BEHAVIOR_PROMPTS=data/eval_behavior_v0/prompts.jsonl
# Formal behaviour measurement is UNRESTRICTED (AGENTS.md P18). This value is
# used only for cheap smoke checks and is recorded as a censored measurement.
BEHAVIOR_MAX_NEW_TOKENS=512

# Files this session's post_run.sh writes per arm; the orchestrator fetches
# exactly these. Experiment 1 drops the INT8, probe and capped-behaviour
# artifacts — see the header of post_run.sh for why.
ARM_ARTIFACTS="train_log.jsonl run_manifest.json eval_holdout_v1.json gen_smoke.json console.log"

# Convenience accessors -------------------------------------------------------
arm_field() { printf '%s' "$1" | cut -d'|' -f"$2"; }
arm_names() { local a; for a in "${ARMS[@]}"; do arm_field "$a" 1; done; }
