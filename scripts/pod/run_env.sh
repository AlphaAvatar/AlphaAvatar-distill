#!/usr/bin/env bash
# Session definition for a GPU pod session. Single source of truth: every other
# script in scripts/pod/ sources this file instead of hardcoding a run name,
# config, checkpoint or HF path.
#
# SESSION: Experiment 1 — recovery-data scaling (logs/PROPOSAL.md §4).
# 24 arms = 6 rungs x 2 seeds x 2 inits, trained on the uniform token-ladder cut.
#
# The session runs on TWO pods, split by initialization so that losing a pod
# costs one init axis rather than half of every curve. POD_ROLE selects the
# slice and must be exported before this file is sourced:
#
#   POD_ROLE=pca   -> the 12 PCA/sandwich-init arms
#   POD_ROLE=rand  -> the 12 random-baseline-init arms
#
# Arms are ordered seed a first, then seed b, and small rungs first. If the
# budget deadline cuts a pod short, what is lost is the tail of the second seed,
# not a whole curve.

SESSION=e1_scaling
SESSION_DATE=20260801
POD_ROLE=${POD_ROLE:-pca}

# Arm entries are name|config|final-step-tag, generated by
# scripts/data/build_experiment1_configs.py. An arm differs from
# configs/stage3/recovery.json only in data source, rung, seed and student_path.
ARMS_PCA=(
  "e1_r0250k_sa_pca|configs/stage3/e1/e1_r0250k_sa_pca.json|step_000324"
  "e1_r0460k_sa_pca|configs/stage3/e1/e1_r0460k_sa_pca.json|step_000570"
