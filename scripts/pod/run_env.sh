  REF_CKPTS=("${REF_CKPTS_RAND[@]}")
else
  REF_CKPTS=("${REF_CKPTS_PCA[@]}")
fi

# Transfer artifacts on the private HF relay (staged from the dev box).
HF_REPO=AlphaAvatar/aadistill-artifacts
