from __future__ import annotations

import hashlib
import json
from pathlib import Path

import pytest

from aadistill.training import lineage as LIN

A = {"model_id": "org/teacher-a", "revision": "a" * 40}
B = {"model_id": "org/teacher-b", "revision": "b" * 40}
PACK = {"blocks.npz": "1" * 64, "ladder.json": "2" * 64, "audit.jsonl": "3" * 64}
SHARDS = {"model-00001.safetensors": "f" * 64, "model-00002.safetensors": "d" * 64}
TOK_A = {"tokenizer.json": "4" * 64, "tokenizer_config.json": "5" * 64}
#: teacher B's tokenizer: the same vocabulary file, another template
TOK_B = {"tokenizer.json": "4" * 64, "tokenizer_config.json": "6" * 64}


def _lineage(teacher=A, root=A, data_teacher=A, mode="thinking", data_mode="thinking", init="e" * 64):
    return {"teacher": {**teacher, "weights_sha256": dict(SHARDS), "rope_theta": 1_000_000,
                        "max_position_embeddings": 40960, "vocab_size": 151936, "chat_template_sha256": "c" * 64},
            "mode": mode, "tokenizer": {"files_sha256": dict(TOK_A)},
            "initialization": {"root_teacher": dict(root), "model_safetensors_sha256": init,
                               "provenance": {"record": "logs/search_record.json", "record_sha256": "7" * 64}},
            "data": [{"files_sha256": PACK, "teacher": dict(data_teacher), "mode": data_mode}]}


def _provenance(teacher=A, shards=None, checkpoint="e" * 64):
    return {"root_teacher_id": f"{teacher['model_id']}@{teacher['revision']}",
            "root_teacher_sha256": LIN.shard_set_sha256(shards or SHARDS), "checkpoint_sha256": checkpoint}


def _observed(**over):
    obs = {"kd_teacher": {**A, "dtype": "bfloat16"}, "loaded_teacher": {**A, "vocab_size": 151936},
           "teacher_snapshot": {"weights_sha256": dict(SHARDS), "rope_theta": 1_000_000.0,
                                "max_position_embeddings": 40960, "chat_template_sha256": "c" * 64},
           "student_config": {"rope_theta": 1_000_000, "max_position_embeddings": 40960, "vocab_size": 151936},
           "student_weights_sha256": "e" * 64, "pack_files_sha256": PACK, "tokenizer_files_sha256": dict(TOK_A),
           "initialization_provenance": _provenance()}
    obs.update(over)
    return obs


def test_one_lineage_passes():
    LIN.require(_lineage(), **_observed())


def test_a_student_of_one_root_is_never_distilled_by_another_teacher():
    with pytest.raises(LIN.LineageError, match="online KD teacher"):
        LIN.require(_lineage(), **_observed(kd_teacher=B, loaded_teacher=B))
    with pytest.raises(LIN.LineageError, match="root teacher"):
        LIN.require(_lineage(root=B), **_observed())
    # the same vocabulary and geometry do not make two teachers one lineage
    with pytest.raises(LIN.LineageError, match="rope_theta"):
        LIN.require(_lineage(), **_observed(student_config={"rope_parameters": {"rope_theta": 5_000_000},
                                                           "max_position_embeddings": 262144, "vocab_size": 151936}))


def test_data_of_another_teacher_or_another_mode_is_refused():
    with pytest.raises(LIN.LineageError, match="generated by"):
        LIN.require(_lineage(data_teacher=B), **_observed())
    with pytest.raises(LIN.LineageError, match="mode"):
        LIN.require(_lineage(data_mode="non_thinking"), **_observed())
    with pytest.raises(LIN.LineageError, match="not a pack the lineage binds"):
        LIN.require(_lineage(), **_observed(pack_files_sha256={**PACK, "blocks.npz": "9" * 64}))


def test_the_bytes_actually_loaded_are_checked():
    with pytest.raises(LIN.LineageError, match="weight shards"):
        LIN.require(_lineage(), **_observed(teacher_snapshot={"weights_sha256": {"model-00001.safetensors": "0" * 64}}))
    with pytest.raises(LIN.LineageError, match="initialization's weights"):
        LIN.require(_lineage(), **_observed(student_weights_sha256="0" * 64))
    with pytest.raises(LIN.LineageError, match="chat_template"):
        LIN.require(_lineage(), **_observed(teacher_snapshot={"chat_template_sha256": "0" * 64}))


def test_an_incomplete_declaration_is_refused_and_every_unit_is_reported():
    with pytest.raises(LIN.LineageError, match="model_id and revision"):
        LIN.require({"teacher": {}, "initialization": {}, "data": []})
    bad = _lineage()
    bad["initialization"].pop("model_safetensors_sha256")
    with pytest.raises(LIN.LineageError) as e:
        LIN.require_all([("u1", _lineage(), _observed()), ("u2", bad, _observed(kd_teacher=B))])
    assert "u2:" in str(e.value) and "u1:" not in str(e.value)


def test_snapshot_facts_read_lfs_blob_names_the_template_and_rope(tmp_path):
    blobs, snap = tmp_path / "blobs", tmp_path / "snap"
    blobs.mkdir()
    snap.mkdir()
    blob = blobs / ("d" * 64)
    blob.write_bytes(b"weights")
    (snap / "model.safetensors").symlink_to(blob)
    (snap / "extra.safetensors").write_bytes(b"x")
    (snap / "config.json").write_text(json.dumps({"rope_parameters": {"rope_theta": 5_000_000},
                                                  "max_position_embeddings": 262144}))
    (snap / "tokenizer_config.json").write_text(json.dumps({"chat_template": "T"}))
    f = LIN.snapshot_facts(snap)
    assert f["weights_sha256"] == {"extra.safetensors": hashlib.sha256(b"x").hexdigest(), "model.safetensors": "d" * 64}
    assert f["rope_theta"] == 5_000_000.0 and f["max_position_embeddings"] == 262144
    assert f["chat_template_sha256"] == hashlib.sha256(b"T").hexdigest()


def test_snapshot_facts_read_the_first_hop_not_a_shared_xet_store_behind_it(tmp_path):
    """2026-11-02: the pod's huggingface_hub linked blobs/<lfs sha256> on to blobs/<xx>/<xet hash>; resolving the
    whole chain read the Xet hash as the shard's sha256 and the lineage gate refused the right teacher."""
    store, blobs, snap = tmp_path / "hub/blobs/a6", tmp_path / "hub/models--org--t/blobs", tmp_path / "snap"
    for d in (store, blobs, snap):
        d.mkdir(parents=True)
    (store / ("a" * 64)).write_bytes(b"weights")
    (blobs / ("3" * 64)).symlink_to(store / ("a" * 64))
    (snap / "model.safetensors").symlink_to(blobs / ("3" * 64))
    (snap / "config.json").write_text(json.dumps({"rope_theta": 1_000_000, "max_position_embeddings": 40960}))
    assert LIN.snapshot_facts(snap)["weights_sha256"] == {"model.safetensors": "3" * 64}


